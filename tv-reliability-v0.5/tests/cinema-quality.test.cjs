'use strict';
// Synthetic-only tests; never start TV, encoder or real Windows input.
const test=require('node:test'),assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const sound=require('../cast/sound.cjs');
const root=path.resolve(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const value=(args,name)=>args[args.indexOf(name)+1];
test('Cinema is a separate higher-quality HLS profile; original interaction unchanged',()=>{
 const dir=path.join(__dirname,'no-real-video-created');
 const base=sound.argsFor(dir);
 const cinema=sound.argsFor(dir,null,0,'cinema');
 const restInteractive=sound.argsFor(dir,null,100,'interactive');
 const restCinema=sound.argsFor(dir,null,101,'cinema');
 assert.equal(value(base,'-hls_flags').includes('discont_start'),false);
 assert.equal(value(restInteractive,'-hls_flags').includes('discont_start'),true);
 assert.equal(value(restCinema,'-hls_flags').includes('discont_start'),true);
 assert.equal(value(base,'-framerate'),'15');
 assert.equal(value(base,'-vf'),'scale=1280:-2');
 assert.equal(value(base,'-crf'),'28');
 assert.equal(value(base,'-hls_time'),'1');
 assert.equal(value(base,'-hls_list_size'),'4');
 assert.equal(value(cinema,'-framerate'),'30');
 assert.equal(value(cinema,'-vf'),'scale=1920:-2');
 assert.equal(value(cinema,'-crf'),'18');
 assert.equal(value(cinema,'-profile:v'),'high');
 assert.equal(value(cinema,'-level'),'4.1');
 assert.equal(value(cinema,'-hls_time'),'2');
 assert.equal(value(cinema,'-hls_list_size'),'18');
 assert.equal(value(cinema,'-g'),'60');
 assert.equal(cinema.includes('zerolatency'),false);
 assert.ok(cinema.includes('-an'),'Video-only Cinema source remains silent until owner opts into audio');
 assert.throws(()=>sound.argsFor(dir,null,0,'unknown'),/Unsupported display quality mode/);
 const av=sound.argsFor(dir,{sampleFormat:'f32le',sampleRate:48000,channels:2},70,'cinema');
 assert.ok(av.includes('pipe:3'));
 assert.equal(value(av,'-b:a'),'192k');
 assert.ok(av.includes('aresample=async=1:first_pts=0'));
});
test('Cinema switches the existing capture without opening a second encoder',()=>{
 const cast=read('cast/server.cjs');
 assert.match(cast,/pendingRestart=\{format:captureFormat\}/);
 assert.match(cast,/capture\.kill\('SIGTERM'\)/);
 assert.match(cast,/SOUND\.argsFor\(SEGMENTS,format,nextSegment,qualityMode\)/);
 assert.match(cast,/SOUND\.qualityProfile\(mode\)/);
 assert.match(cast,/now-lastQualityAt<5000/);
 assert.match(cast,/peer!==LAN_IP/);
 assert.match(cast,/qualityMode:h\.qualityMode,qualityVersion:h\.qualityVersion/);
});
test('TV-selected quality never grants mouse permission and keeps existing session policy',()=>{
 const server=read('viewer/server.cjs'),ui=read('viewer/web/immersive.js');
 assert.match(server,/tokenMatches\(auth\)\|\|!active\(\)/);
 assert.match(server,/route==='\/api\/quality'/);
 assert.match(server,/enabled=false;enabledUntil=0/);
 assert.match(server,/if\(\(await sourceAudioInfo\(\)\)\.qualityMode==='cinema'\)/);
 assert.match(server,/Cinema mode does not permit Windows mouse input/);
 assert.match(server,/Cinema mode is view-only/);
 assert.match(server,/controller\.hostname!==LAN\|\|controller\.port!=='43196'/);
 assert.match(ui,/pauseEpoch\+\+;armed=false;qualitySwitching=true/);
 assert.match(ui,/if\(qualityMode==='cinema'\)return;/);
 assert.match(ui,/qualityAwaitingReload&&streamFresh/);
 assert.match(ui,/el\('enable'\)\.disabled=armed\|\|pausePending\|\|qualitySwitching\|\|qualityMode==='cinema'/);
});
